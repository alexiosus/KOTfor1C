import * as vscode from 'vscode';
import { isProcessYamlFile, isProcessTestSettingsYamlFile, isScenarioYamlFile, isTestSettingsYamlFile } from './yamlValidator';
import { parsePhaseSwitcherMetadata } from './phaseSwitcherMetadata';
import { findProcessHeaderFieldLines, findScenarioHeaderFieldLines, findTestSettingsFieldLines } from './yamlHeaderFields';
import { buildScenarioVariantPreview } from './scenarioParameterUtils';
import { projectedProjectScenario } from './projectLibraryIntegration';

function createActionHint(
    document: vscode.TextDocument,
    line: number,
    command: string,
    tooltipText: string,
    labelText = ' ✎ '
): vscode.InlayHint {
    const position = new vscode.Position(line, document.lineAt(line).text.length);
    const labelPart = new vscode.InlayHintLabelPart(labelText);
    labelPart.command = {
        title: tooltipText,
        command,
        arguments: [document.uri]
    };

    const hint = new vscode.InlayHint(position, [labelPart], vscode.InlayHintKind.Type);
    hint.paddingLeft = true;
    hint.paddingRight = false;
    return hint;
}

export class ScenarioHeaderInlayHintsProvider implements vscode.InlayHintsProvider {
    private readonly changes = new vscode.EventEmitter<void>();
    readonly onDidChangeInlayHints = this.changes.event;

    refresh(): void { this.changes.fire(); }
    dispose(): void { this.changes.dispose(); }

    provideInlayHints(
        document: vscode.TextDocument,
        _range: vscode.Range,
        _token: vscode.CancellationToken
    ): vscode.ProviderResult<vscode.InlayHint[]> {
        const hints: vscode.InlayHint[] = [];

        const isProcess = isProcessYamlFile(document);
        if (isProcess || isScenarioYamlFile(document)) {
            const metadata = parsePhaseSwitcherMetadata(document.getText());
            const projected = projectedProjectScenario(document);
            const isMainScenario = !isProcess && (projected ? !!projected.tabName?.trim() : metadata.hasTab);
            const fieldLines = isProcess ? findProcessHeaderFieldLines(document) : findScenarioHeaderFieldLines(document);
            const variants = buildScenarioVariantPreview(document.getText());
            if (!isProcess && variants.count !== '1') {
                const line = document.getText().split(/\r\n|\n/u).findIndex(value => /^ПараметрыСценария\s*:/u.test(value));
                if (line >= 0) {
                    const hint = new vscode.InlayHint(new vscode.Position(line, document.lineAt(line).text.length),
                        vscode.l10n.t('Variants: {0}', variants.count), vscode.InlayHintKind.Type);
                    const tooltip = new vscode.MarkdownString();
                    tooltip.appendMarkdown(vscode.l10n.t('Parameter combinations generated by the compiler.') + '\n\n');
                    variants.samples.forEach((sample, index) => {
                        tooltip.appendMarkdown(`**${index + 1}**\n\n`);
                        tooltip.appendCodeblock(Object.entries(sample).map(([name, value]) =>
                            `${name} = ${value.length > 256 ? value.slice(0, 256) + '…' : value}`).join('\n'), 'text');
                    });
                    if (variants.truncated) { tooltip.appendMarkdown(vscode.l10n.t('Showing the first {0} combinations.', String(variants.samples.length))); }
                    hint.tooltip = tooltip;
                    hint.paddingLeft = true;
                    hints.push(hint);
                }
            }

            if ((isProcess || isMainScenario) && fieldLines.fileTypeLine !== null) {
                hints.push(createActionHint(
                    document,
                    fieldLines.fileTypeLine,
                    isProcess ? 'kotTestToolkit.openProcessTestSettingsFromEditor' : 'kotTestToolkit.openMainScenarioTestSettingsFromEditor',
                    vscode.l10n.t('Open test settings'),
                    ' ⚙ '
                ));
            }

            const groupActionLine = fieldLines.fileTypeLine ?? fieldLines.nameLine;
            if ((isProcess || isMainScenario) && groupActionLine !== null) {
                hints.push(createActionHint(document, groupActionLine, 'kotTestToolkit.changeScenarioGroup',
                    vscode.l10n.t('Change group'), ' 📁 '));
            }

            if (fieldLines.nameLine !== null) {
                hints.push(createActionHint(
                    document,
                    fieldLines.nameLine,
                    isProcess ? 'kotTestToolkit.renameProcessFromEditor'
                        : isMainScenario ? 'kotTestToolkit.renameScenarioFromEditor' : 'kotTestToolkit.changeNestedScenarioName',
                    isProcess ? vscode.l10n.t('Rename process')
                        : isMainScenario ? vscode.l10n.t('Rename scenario') : vscode.l10n.t('Change nested scenario name')
                ));
            }

            const metadataActionLine = fieldLines.nameLine ?? fieldLines.fileTypeLine;
            if (metadataActionLine !== null) {
                hints.push(createActionHint(document, metadataActionLine, 'kotTestToolkit.openProjectMetadata',
                    vscode.l10n.t('Open project metadata'), ' ⚙ '));
            }

            if (fieldLines.codeLine !== null) {
                hints.push(createActionHint(
                    document,
                    fieldLines.codeLine,
                    isProcess ? 'kotTestToolkit.changeProcessCodeFromEditor'
                        : isMainScenario ? 'kotTestToolkit.renameScenarioFromEditor' : 'kotTestToolkit.changeNestedScenarioCode',
                    isProcess ? vscode.l10n.t('Change process code')
                        : isMainScenario ? vscode.l10n.t('Rename scenario') : vscode.l10n.t('Change nested scenario code')
                ));
            }

            if (fieldLines.systemFunctionLine !== null) {
                hints.push(createActionHint(
                    document,
                    fieldLines.systemFunctionLine,
                    'kotTestToolkit.changeScenarioSystemFunctionFromEditor',
                    vscode.l10n.t('Change system function')
                ));
            }

            if (fieldLines.systemFunctionUidLine !== null) {
                hints.push(createActionHint(
                    document,
                    fieldLines.systemFunctionUidLine,
                    'kotTestToolkit.changeScenarioSystemFunctionFromEditor',
                    vscode.l10n.t('Change system function')
                ));
            }

            const descriptionActionLine = fieldLines.kotDescriptionLine ?? (!isProcess ? metadataActionLine : null);
            if (descriptionActionLine !== null) {
                hints.push(createActionHint(
                    document,
                    descriptionActionLine,
                    'kotTestToolkit.generateScenarioDescriptionWithAi',
                    vscode.l10n.t('Describe with AI'),
                    ` ${vscode.l10n.t('Describe with AI')} `
                ));
            }

            return hints;
        }

        const isProcessSettings = isProcessTestSettingsYamlFile(document);
        if (!isProcessSettings && !isTestSettingsYamlFile(document)) {
            return hints;
        }

        const testFieldLines = findTestSettingsFieldLines(document);
        const changeLinkTooltip = isProcessSettings ? vscode.l10n.t('Change linked process') : vscode.l10n.t('Change linked scenario');
        const changeLinkCommand = isProcessSettings
            ? 'kotTestToolkit.changeProcessTestSettingsFromEditor'
            : 'kotTestToolkit.changeTestSettingsScenarioFromEditor';

        if (testFieldLines.codeLine !== null) {
            hints.push(createActionHint(document, testFieldLines.codeLine, changeLinkCommand, changeLinkTooltip));
        }
        if (testFieldLines.nameLine !== null) {
            hints.push(createActionHint(document, testFieldLines.nameLine, changeLinkCommand, changeLinkTooltip));
        }
        if (testFieldLines.scenarioUidLine !== null) {
            hints.push(createActionHint(document, testFieldLines.scenarioUidLine, changeLinkCommand, changeLinkTooltip));
        }
        if (testFieldLines.scenarioNameLine !== null) {
            hints.push(createActionHint(document, testFieldLines.scenarioNameLine, changeLinkCommand, changeLinkTooltip));
        }
        if (testFieldLines.etalonBaseNameLine !== null) {
            hints.push(createActionHint(document, testFieldLines.etalonBaseNameLine, 'kotTestToolkit.changeTestSettingsEtalonBaseFromEditor', vscode.l10n.t('Change etalon base')));
        }
        if (testFieldLines.modelDbIdLine !== null) {
            hints.push(createActionHint(document, testFieldLines.modelDbIdLine, 'kotTestToolkit.changeTestSettingsEtalonBaseFromEditor', vscode.l10n.t('Change etalon base')));
        }
        if (testFieldLines.userProfileLine !== null) {
            hints.push(createActionHint(document, testFieldLines.userProfileLine, 'kotTestToolkit.changeTestSettingsUserProfileFromEditor', vscode.l10n.t('Change test user profile')));
        }

        return hints;
    }
}
